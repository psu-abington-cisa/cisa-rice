#!/usr/bin/env python3
"""Generate the vector CISA marks in assets/.

  assets/cisa-logo.svg      the original CISA badge, redrawn as a pure vector
  assets/seal-ring.svgfrag  ring lettering for the "ci seal" (from the CISA logo
                            concepts canvas), as outlines with a {{FG}} fill placeholder

All lettering is converted to outline paths with fontTools and laid out glyph by
glyph along arcs, so nothing needs fonts at render time and every SVG renderer
(including librsvg, which has no <textPath>) draws it identically.

Needs: python3-fonttools, fonts-montserrat, fonts-jetbrains-mono.
Run:   python3 dev/make-logo.py
"""
import math
import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ASSETS = pathlib.Path(__file__).resolve().parent.parent / "assets"


class Font:
    def __init__(self, path):
        self.tt = TTFont(path)
        self.glyphs = self.tt.getGlyphSet()
        self.cmap = self.tt.getBestCmap()
        self.upem = self.tt["head"].unitsPerEm
        self.hmtx = self.tt["hmtx"]
        self.cap = self.tt["OS/2"].sCapHeight / self.upem

    def width(self, ch, size):
        return self.hmtx[self.cmap[ord(ch)]][0] / self.upem * size


def arc_text(font, text, radius, mid_deg, size, spacing, outward_up, fill,
             cx=500.0, cy=500.0, fit_deg=None):
    """Lay out `text` centred on `mid_deg` (screen degrees: 0 = right, 90 = down).

    outward_up=True : letters stand on the circle, tops outward (reads clockwise).
    outward_up=False: letters hang inside, tops toward the centre (reads counter-clockwise).
    `radius` is where the letters' vertical centre sits. With `fit_deg`, the letter
    spacing is chosen so the text spans exactly that many degrees.
    """
    base_r = radius - font.cap * size / 2 if outward_up else radius + font.cap * size / 2
    widths = [font.width(c, size) for c in text]
    if fit_deg is not None:
        spacing = (math.radians(fit_deg) * base_r - sum(widths)) / (len(text) - 1)
    total = sum(widths) + spacing * (len(text) - 1)
    direction = 1 if outward_up else -1
    theta = math.radians(mid_deg) - direction * (total / base_r) / 2
    s = size / font.upem
    parts = []
    for ch, w in zip(text, widths):
        centre = theta + direction * (w / 2) / base_r
        if ch != " ":
            x = cx + base_r * math.cos(centre)
            y = cy + base_r * math.sin(centre)
            rot = centre + (math.pi / 2 if outward_up else -math.pi / 2)
            c, sn = math.cos(rot), math.sin(rot)
            # glyph space (y up): scale, flip y, centre the advance, rotate, move onto the arc
            matrix = (s * c, s * sn, s * sn, -s * c, x - (w / 2) * c, y - (w / 2) * sn)
            pen = SVGPathPen(font.glyphs)
            font.glyphs[font.cmap[ord(ch)]].draw(TransformPen(pen, matrix))
            parts.append(pen.getCommands())
        theta += direction * (w + spacing) / base_r
    return f'<path fill="{fill}" d="{" ".join(parts)}"/>'


