def seal_ring():
    """Ring lettering for the ci seal, in a 400x400 box centred at (200, 200)."""
    f = Font("/usr/share/fonts/truetype/jetbrains-mono/JetBrainsMono-Medium.ttf")
    top = arc_text(f, "CYBERSECURITY & IT · STUDENT ASSOCIATION", 148, 270, 18, 0, True,
                   "{{FG}}", cx=200, cy=200, fit_deg=226)
    bottom = arc_text(f, "PENN STATE ABINGTON", 150, 90, 18, 3.2, False, "{{FG}}", cx=200, cy=200)
    return f"<!-- generated by dev/make-logo.py -->\n{top}\n{bottom}\n"


for name, content in (("cisa-logo.svg", badge()), ("seal-ring.svgfrag", seal_ring())):
    out = ASSETS / name
    out.write_text(content)
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
